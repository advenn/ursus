func writeFile(t *testing.T, name, content string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), name)
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

const salesCSV = `region,rep,amount,qty,active
eu,ann,10.5,1,true
us,bob,20.0,2,false
eu,cat,,3,true
apac,dan,40.25,4,false
`

// TestScanCSVInfersTypes checks the inference lattice end to end. Getting this
// wrong is not a crash — it is a String column where a number was wanted, and the
// user finding out three operations later.
func TestScanCSVInfersTypes(t *testing.T) {
	df, err := ursus.ScanCSV(writeFile(t, "sales.csv", salesCSV)).
		Collect(t.Context(), ursus.WithVerify())
	if err != nil {
		t.Fatal(err)
	}

	want := []dtype.DataType{dtype.String, dtype.String, dtype.Float64, dtype.Int64, dtype.Bool}
	for i, w := range want {
		if got := df.Schema().Field(i).Type; got != w {
			t.Errorf("column %q inferred as %s, want %s",
				df.Schema().Field(i).Name, got, w)
		}
	}
	if df.Height() != 4 {
		t.Errorf("got %d rows, want 4\n%s", df.Height(), df)
	}
	// The empty amount on row 3 is a null, not a zero. Reading it as 0 would be a
	// silently wrong number in every aggregate downstream.
	if _, ok, err := df.At[float64](2, "amount"); err != nil {
		t.Fatal(err)
	} else if ok {
		t.Errorf("an empty numeric field must be null, not 0:\n%s", df)
	}
}

// TestScanCSVEmptyStringIsNotNull is the other half of the same decision. For a
// String column "" is a value; conflating it with null would be unrecoverable.
func TestScanCSVEmptyStringIsNotNull(t *testing.T) {
	path := writeFile(t, "s.csv", "a,b\n,x\n")
	df, err := ursus.ScanCSV(path).Collect(t.Context())
	if err != nil {
		t.Fatal(err)
	}
	v, ok, err := df.At[string](0, "a")
	if err != nil {
		t.Fatal(err)
	}
	if !ok || v != "" {
		t.Errorf("empty String field = (%q, valid %v), want (\"\", true)", v, ok)
	}
}

// TestScanCSVProjectionSkipsParsing is the point of pushing projection into a
// reader. The unselected column is deliberately unparseable as its inferred type:
// if the reader were parsing every column, this query would fail.
func TestScanCSVProjectionSkipsParsing(t *testing.T) {
	// `n` infers as Int64 from the sample, then row 3 holds a word. Selecting only
	// `keep` must succeed; selecting `n` must fail.
	content := "keep,n\na,1\nb,2\nc,not-a-number\n"
	path := writeFile(t, "p.csv", content)

	df, err := ursus.ScanCSV(path, ursus.WithInferRows(2)).
		Select(ursus.Col("keep")).
		Collect(t.Context(), ursus.WithVerify())
	if err != nil {
		t.Fatalf("the unselected column must never be parsed: %v", err)
	}
	if df.Height() != 3 || df.Width() != 1 {
		t.Errorf("got %dx%d, want 3x1\n%s", df.Height(), df.Width(), df)
	}

	if _, err := ursus.ScanCSV(path, ursus.WithInferRows(2)).
		Select(ursus.Col("n")).Collect(t.Context()); err == nil {
		t.Error("selecting the bad column should fail; otherwise this test proves nothing")
	}
}

// TestScanCSVValueErrorQuality pins the error contract. A dataframe library is
// used interactively, and "cannot parse int" on a ten-million-row file is useless.
func TestScanCSVValueErrorQuality(t *testing.T) {
	// A quoted field with an embedded newline before the bad row, so the physical
	// line and the logical record deliberately disagree.
	content := "id,n\n\"a\nb\",1\nc,oops\n"
	path := writeFile(t, "bad.csv", content)

	_, err := ursus.ScanCSV(path, ursus.WithInferRows(1)).Collect(t.Context())
	if err == nil {
		t.Fatal("expected a parse error")
	}
	msg := err.Error()

	for _, want := range []string{
		`"n"`,     // the column BY NAME
		`"oops"`,  // the text found
		"Int64",   // the type expected
		"row 2",   // the DATA row, which is the position in the frame
		"line 4",  // the physical line, which differs from the row
		"bad.csv", // which file
	} {
		if !strings.Contains(msg, want) {
			t.Errorf("error should mention %s:\n%v", want, err)
		}
	}
	if !errors.Is(err, uerr.ErrValue) {
		t.Errorf("kind should be Value: %v", err)
	}
	if errors.Is(err, uerr.ErrInternal) {
		t.Errorf("malformed input is not an ursus bug; the message would send the "+
			"user to the issue tracker over a stray comma:\n%v", err)
	}
}


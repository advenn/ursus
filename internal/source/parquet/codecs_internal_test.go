// boundedCompressions are the codecs the package's init replaces with boundedCodec.
var boundedCompressions = []compress.Compression{compress.Codecs.Snappy, compress.Codecs.Gzip,
	compress.Codecs.Brotli, compress.Codecs.Zstd}

// arrowCodec is the registry's codec for c, ursus's bounded one, and the codec it
// replaced, arrow-go's.
func arrowCodec(t testing.TB, c compress.Compression) (bounded, was compress.Codec) {
	t.Helper()
	got, err := compress.GetCodec(c)
	if err != nil {
		t.Fatal(err)
	}
	b, ok := got.(boundedStreaming)
	if !ok {
		t.Fatalf("%s: arrow-go's registry holds %T, not ursus's bounded codec", c, got)
	}
	return got, b.Codec
}

// withArrowCodecs runs fn with arrow-go's own codecs in its registry in place of
// ursus's, and puts ursus's back. Nothing else may read the registry meanwhile: the
// package's tests do not run in parallel.
func withArrowCodecs(t testing.TB, fn func()) {
	t.Helper()
	for _, c := range boundedCompressions {
		bounded, was := arrowCodec(t, c)
		compress.RegisterCodec(c, was)
		defer compress.RegisterCodec(c, bounded)
	}
	fn()
}

// codecInputs are generated bytes to compress: random, runs of random lengths, and
// words, at sizes about a Zstandard block's 128 KiB and a Snappy varint's steps.
func codecInputs() [][]byte {
	rng := rand.New(rand.NewPCG(520, 1))
	words := []string{"AIR", "MAIL ", "TRUCK", "DELIVER IN PERSON ", "é漢字", "\x00"}
	var out [][]byte
	for _, n := range []int{0, 1, 7, 127, 128, 4096, 65_536, 131_072, 131_073, 300_001} {
		random, runs, text := make([]byte, n), make([]byte, 0, n), make([]byte, 0, n)
		for i := range random {
			random[i] = byte(rng.Uint32())
		}
		for len(runs) < n {
			runs = append(runs, bytes.Repeat([]byte{byte(rng.IntN(4))}, 1+rng.IntN(300))...)
		}
		for len(text) < n {
			text = append(text, words[rng.IntN(len(words))]...)
		}
		out = append(out, random, runs[:n], text[:n])
	}
	return out
}

// codecStreams are src compressed as writers compress it under codec c, whose
// arrow-go codec is was: was's encoding at its fastest level and at its default; and
// Zstandard without a content size and as two frames, gzip as two members.
func codecStreams(t testing.TB, c compress.Compression, was compress.Codec, src []byte) [][]byte {
	t.Helper()
	enc := func(level int, b []byte) []byte {
		return was.EncodeLevel(make([]byte, was.CompressBound(int64(max(len(b), 1)))), b, level)
	}
	half := len(src) / 2
	switch c {
	case compress.Codecs.Zstd:
		var buf bytes.Buffer
		w, err := zstd.NewWriter(&buf, zstd.WithEncoderConcurrency(1))
		if err != nil {
			t.Fatal(err)
		}
		if _, err := w.Write(src); err != nil {
			t.Fatal(err)
		}
		if err := w.Flush(); err != nil {
			t.Fatal(err)
		}
		if err := w.Close(); err != nil {
			t.Fatal(err)
		}
		return [][]byte{enc(1, src), enc(compress.DefaultCompressionLevel, src), buf.Bytes(),
			append(enc(1, src[:half]), enc(1, src[half:])...)}
	case compress.Codecs.Gzip:
		return [][]byte{enc(1, src), enc(compress.DefaultCompressionLevel, src),
			append(enc(1, src[:half]), enc(1, src[half:])...)}
	case compress.Codecs.Brotli:
		return [][]byte{enc(1, src), enc(5, src)}
	}
	return [][]byte{was.Encode(make([]byte, was.CompressBound(int64(len(src)))), src)}
}

// TestBoundedCodecsDecodeAsTheCodecsTheyReplace (step 520): each codec the package's
// init registers, against the codec it replaced, arrow-go's, on generated bytes
// (codecInputs) compressed as writers compress them (codecStreams), cut short and with
// a byte flipped, decoded into a buffer of their size, shorter, longer, of a
// capacity past its length, and empty:
//
//   - where arrow-go's codec decodes into the buffer, the bounded one decodes the same
//     bytes into it;
//   - where the bounded codec decodes, it decodes what arrow-go's decodes of the
//     stream into a nil buffer, into its buffer;
//   - where it refuses a stream as past its buffer, the stream holds more than the
//     buffer, its capacity for Zstandard and Snappy and its length for gzip and
//     Brotli, as each codec reads a buffer, or is corrupt;
//   - where arrow-go's codec made a buffer of its own, the bounded one refuses, or
//     decodes as above: as past the buffer, or, a Zstandard block's output past it,
//     with klauspost's own refusal of the block;
//   - a nil buffer, from a caller that is not arrow-go's page reader, decodes as
//     arrow-go's codec decodes it;
//   - encoding, at each level, and its bound are arrow-go's codec's, byte for byte.
func TestBoundedCodecsDecodeAsTheCodecsTheyReplace(t *testing.T) {
	inputs := codecInputs()
	for _, c := range boundedCompressions {
		t.Run(c.String(), func(t *testing.T) {
			rng := rand.New(rand.NewPCG(520, uint64(c)))
			bounded, was := arrowCodec(t, c)
			byCap := c == compress.Codecs.Zstd || c == compress.Codecs.Snappy
			var n alike
			for _, src := range inputs {
				if len(src) <= 65_536 {
					for _, level := range []int{compress.DefaultCompressionLevel, 1} {
						dst := was.CompressBound(int64(max(len(src), 1)))
						a := was.EncodeLevel(make([]byte, dst), src, level)
						b := bounded.EncodeLevel(make([]byte, dst), src, level)
						if !bytes.Equal(a, b) {
							t.Fatalf("%d bytes at level %d encode otherwise", len(src), level)
						}
					}
					if a, b := was.Encode(nil, src), bounded.Encode(nil, src); !bytes.Equal(a, b) {
						t.Fatalf("%d bytes encode otherwise", len(src))
					}
					if was.CompressBound(int64(len(src))+1) != bounded.CompressBound(int64(len(src))+1) {
						t.Fatalf("the bound of %d bytes differs", len(src)+1)
					}
				}
				for _, enc := range codecStreams(t, c, was, src) {
					variants := [][]byte{enc, enc[:len(enc)/2]}
					if len(enc) > 0 {
						flipped := slices.Clone(enc)
						flipped[rng.IntN(len(enc))] ^= 1 << rng.IntN(8)
						variants = append(variants, flipped)
					}
					for _, s := range variants {
						all, allErr := compress.Decode(was, nil, s)
						if b, err := compress.Decode(bounded, nil, s); (err == nil) != (allErr == nil) ||
							!bytes.Equal(b, all) {
							t.Fatalf("%d bytes into a nil buffer: arrow-go's codec %d bytes, %v; the bounded %d, %v",
								len(src), len(all), allErr, len(b), err)
						}
						k := len(src)
						for _, shape := range [][2]int{{k, k}, {k - 1, k - 1}, {k - 1, k + 64}, {k + 1, k + 1}, {0, 0}} {
							if shape[0] >= 0 {
								n.decode(t, was, bounded, s, shape[0], shape[1], byCap, all, allErr)
							}
						}
					}
				}
			}
			t.Logf("%s: %d decoded alike into the buffer, %d refused by both, %d refused as past the buffer "+
				"where arrow-go's made one of its own, %d refused otherwise there, %d refused as past it where "+
				"arrow-go's refused too, %d decoded whole where arrow-go's refused or made its own",
				c, n.same, n.refused, n.past, n.blockPast, n.pastRefused, n.whole)
		})
	}
}

// alike counts decode's outcomes.
type alike struct{ same, refused, past, pastRefused, blockPast, whole int }

// decode decodes s with was, arrow-go's codec, and bounded, each into a buffer of
// length l and capacity c, and fails t where the bounded codec's answer is not as
// TestBoundedCodecsDecodeAsTheCodecsTheyReplace says. byCap is whether the codec
// reads a buffer to its capacity; all and allErr are what was decodes of s into a
// nil buffer.
func (n *alike) decode(t *testing.T, was, bounded compress.Codec, s []byte, l, c int, byCap bool,
	all []byte, allErr error) {
	t.Helper()
	dw, db := make([]byte, l, c), make([]byte, l, c)
	outW, errW := compress.Decode(was, dw, s)
	outB, errB := compress.Decode(bounded, db, s)
	in := func(out, buf []byte) bool { return len(out) == 0 || unsafe.SliceData(out) == unsafe.SliceData(buf) }
	bound := l
	if byCap {
		bound = c
	}
	inPlace := errW == nil && in(outW, dw)
	switch {
	case inPlace && (errB != nil || !bytes.Equal(outB, outW) || !in(outB, db)):
		t.Fatalf("a stream of %d bytes into [%d:%d]: arrow-go's codec decodes %d bytes into the buffer, "+
			"the bounded %d, %v", len(s), l, c, len(outW), len(outB), errB)
	case errB == nil && (allErr != nil || !bytes.Equal(outB, all) || !in(outB, db)):
		t.Fatalf("a stream of %d bytes into [%d:%d]: the bounded codec decodes %d bytes, not the %d it holds, "+
			"%v; arrow-go's codec %v", len(s), l, c, len(outB), len(all), allErr, errW)
	case errors.Is(errB, errPast) && allErr == nil && len(all) <= bound:
		t.Fatalf("a stream of %d bytes into [%d:%d]: the bounded codec refuses it as past the buffer, and it "+
			"holds %d bytes", len(s), l, c, len(all))
	case inPlace:
		n.same++
	case errB == nil:
		n.whole++
	case errors.Is(errB, errPast) && errW == nil:
		n.past++
	case errors.Is(errB, errPast):
		n.pastRefused++
	case errW == nil:
		n.blockPast++
	default:
		n.refused++
	}
}

// codecFiles are every Parquet file under testdata: the fixtures other engines wrote,
// the flip sweep's two of ursus's, and pyarrow's and Polars's of every codec they
// write (testdata/parquet/codecs, bench/scripts/oracle/record_codecs.py).
func codecFiles(t *testing.T) map[string][]byte {
	t.Helper()
	files := map[string][]byte{}
	for _, g := range []string{"parquet/*.parquet", "parquet/codecs/*.parquet", "oracle/flips/*.parquet"} {
		paths, err := filepath.Glob(filepath.Join("..", "..", "..", "testdata", g))
		if err != nil || len(paths) == 0 {
			t.Fatalf("%s: %v, %d files", g, err, len(paths))
		}
		for _, p := range paths {
			b, err := os.ReadFile(p)
			if err != nil {
				t.Fatal(err)
			}
			files[strings.TrimPrefix(p, filepath.Join("..", "..", "..", "testdata")+string(filepath.Separator))] = b
		}
	}
	return files
}

// chunkCodecs are the codecs of b's column chunks, b a Parquet file.
func chunkCodecs(t *testing.T, b []byte) []compress.Compression {
	t.Helper()
	r, err := file.NewParquetReader(bytes.NewReader(b))
	if err != nil {
		t.Fatal(err)
	}
	defer r.Close()
	var out []compress.Compression
	md := r.MetaData()
	for g := range md.NumRowGroups() {
		for c := range md.RowGroup(g).NumColumns() {
			cc, err := md.RowGroup(g).ColumnChunk(c)
			if err != nil {
				t.Fatal(err)
			}
			out = append(out, cc.Compression())
		}
	}
	return out
}

// readBatches reads b whole on one thread, as its batches and its schema.
func readBatches(ctx context.Context, b []byte) ([]*data.Batch, error) {
	s := New([]Opener{func(context.Context) (parquet.ReaderAtSeeker, io.Closer, error) {
		return bytes.NewReader(b), nil, nil
	}}, "codecs.parquet", Options{})
	bs, err := s.Open(ctx, source.ScanSpec{Threads: 1, BatchSize: 128})
	if err != nil {
		return nil, err
	}
	defer bs.Close()
	var out []*data.Batch
	for {
		bt, err := bs.Next(ctx)
		if errors.Is(err, io.EOF) {
			return out, nil
		}
		if err != nil {
			return nil, err
		}
		out = append(out, bt)
	}
}

// TestEveryParquetFileReadsAsWithArrowGosCodecs (step 520): no file a writer made is
// refused for its pages' bound. Every Parquet file under testdata (codecFiles), which
// between them hold every codec ursus reads, V1 and V2 data pages, dictionaries and
// lists, and a frame ursus wrote under each codec it writes, read with the reader's
// own pages and without, in batches, answers the same with ursus's codecs in arrow-go's
// registry as with arrow-go's own, error and all. ursus's writer, its encoding
// arrow-go's codecs', writes the same bytes with either.
func TestEveryParquetFileReadsAsWithArrowGosCodecs(t *testing.T) {
	ctx := t.Context()
	files := codecFiles(t)

	batches, err := readBatches(ctx, files[filepath.Join("parquet", "codecs", "pyarrow_zstd_v2.parquet")])
	if err != nil || len(batches) == 0 {
		t.Fatalf("pyarrow's Zstandard file: %v, %d batches", err, len(batches))
	}
	write := func(c compress.Compression) []byte {
		var buf bytes.Buffer
		w, err := NewWriter(&buf, batches[0].Schema(), WriteOptions{Compression: c, RowGroupRows: 200, Stats: true})
		if err != nil {
			t.Fatal(err)
		}
		for _, b := range batches {
			if err := w.WriteBatch(b); err != nil {
				t.Fatal(err)
			}
		}
		if err := w.Close(); err != nil {
			t.Fatal(err)
		}
		return buf.Bytes()
	}
	for _, c := range []compress.Compression{compress.Codecs.Uncompressed, compress.Codecs.Snappy,
		compress.Codecs.Gzip, compress.Codecs.Brotli, compress.Codecs.Zstd, compress.Codecs.Lz4Raw} {
		mine := write(c)
		var theirs []byte
		withArrowCodecs(t, func() { theirs = write(c) })
		if !bytes.Equal(mine, theirs) {
			t.Errorf("ursus's writer, %s: %d bytes with ursus's codecs, %d with arrow-go's", c, len(mine), len(theirs))
		}
		files["ursus, "+c.String()] = mine
	}

	seen := map[compress.Compression]bool{}
	for name, b := range files {
		for _, c := range chunkCodecs(t, b) {
			seen[c] = true
		}
		for _, own := range []bool{true, false} {
			mine, errMine := readTwin(ctx, b, 100, own)
			var theirs []string
			var errTheirs error
			withArrowCodecs(t, func() { theirs, errTheirs = readTwin(ctx, b, 100, own) })
			switch {
			case (errMine == nil) != (errTheirs == nil) || errMine != nil && errMine.Error() != errTheirs.Error():
				t.Errorf("%s, own pages %v: ursus's codecs answer %v, arrow-go's %v", name, own, errMine, errTheirs)
			case !slices.Equal(mine, theirs):
				t.Errorf("%s, own pages %v: the frames differ", name, own)
			case errMine == nil && strings.HasPrefix(name, filepath.Join("parquet", "codecs")) && len(mine) == 0:
				t.Errorf("%s: read as no batches", name)
			}
		}
	}
	for _, c := range boundedCompressions {
		if !seen[c] {
			t.Errorf("no file under testdata holds a chunk of %s", c)
		}
	}
	if !seen[compress.Codecs.Lz4Raw] {
		t.Error("no file under testdata holds a chunk of LZ4_RAW")
	}
}

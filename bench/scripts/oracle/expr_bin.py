"""The expr_bin group: the binary namespace (expr_bin_test.go, step 274) and
bin.reinterpret, on Polars' frames and over generated bytes.
"""

from __future__ import annotations

import polars as pl

from . import Case, case
from .gen import Gen

c = pl.col
B = pl.col("b").bin


def binary(name: str, vals: list) -> pl.Series:
    return pl.Series(name, vals, dtype=pl.Binary)


BF = pl.DataFrame([
    binary("b", [b"hello", None, b"", b"\x00\xffab", b"ell"]),
    binary("p", [b"he", b"x", None, b"\x00", b"ll"]),
    pl.Series("i", [1, 0, 0, -1, 5], dtype=pl.Int64),
    pl.Series("n", [2, 1, 1, 3, None], dtype=pl.Int64),
])
HELLO = pl.DataFrame([binary("b", [b"hello"])])
ROWS = pl.DataFrame([binary("b", [b"hello"] * 4), pl.Series("o", [1, None, 1, 0], dtype=pl.Int64),
                     pl.Series("l", [None, 2, 0, 2], dtype=pl.Int64)])
AB = pl.DataFrame([binary("b", [b"ab", b"ab"]), pl.Series("i", [5, -3], dtype=pl.Int64)])
TEXT = pl.DataFrame([binary("b", [b"6869", b"zz", None])])
B64 = pl.DataFrame([binary("b", [b"aGk=", b"aGk"])])
REINT = pl.DataFrame([binary("b", [b"\x01\x00\x00\x00", b"\xff\xff\xff\xff", None, b"\x01\x00", b"\x01\x00\x00\x00\x02\x00\x00\x00"])])
ONE = pl.DataFrame([binary("b", [b"\x00\x00\x00\x00\x00\x00\xf0\x3f"])])
I128 = pl.DataFrame([binary("b", [b"\x01" + b"\x00" * 15])])


def sel(*exprs: pl.Expr):
    return lambda df: df.select(*exprs)


def one(name: str, e: pl.Expr, frame: pl.DataFrame = BF, **opts) -> Case:
    return case(name, frame, sel(e.alias("r")), **opts)


def cases() -> list[Case]:
    g = Gen(49910)
    n = 150
    gen_bytes = g.frame(g.binary(n, name="b"), g.binary(n, null_rate=0.05, name="p"), g.ints(n, pl.Int64, lo=-6, hi=6, name="i"),
                        g.ints(n, pl.Int64, lo=0, hi=5, name="n"))
    four = g.frame(pl.Series("b", [None if v is None else bytes(int(x) for x in g.rng.integers(0, 256, 4)) for v in g.bools(n).to_list()],
                             dtype=pl.Binary))
    eight = g.frame(pl.Series("b", [None if v is None else bytes(int(x) for x in g.rng.integers(0, 256, 8)) for v in g.bools(n).to_list()],
                              dtype=pl.Binary))
    texts = g.frame(g.strings(n, alphabet="0123456789abcdefABCDEFzz", maxlen=6, edges=False, name="s").cast(pl.Binary).alias("b"))
    return [
        one("contains", B.contains(b"ll")), one("contains_nothing", B.contains(b"")), one("contains_row", B.contains(c("p"))),
        one("starts_with", B.starts_with(b"he")), one("starts_with_row", B.starts_with(c("p"))),
        one("ends_with", B.ends_with(b"ab")), one("ends_with_text", B.ends_with("ab")),
        one("get", B.get(0, null_on_oob=True)), one("get_end", B.get(-1, null_on_oob=True)), one("get_row", B.get(c("i"), null_on_oob=True)),
        one("head", B.head(2)), one("head_all_but", B.head(-2)), one("tail", B.tail(2)), one("tail_all_but", B.tail(-2)),
        one("head_row", B.head(c("n"))),
        one("slice", B.slice(1, 2)), one("slice_end", B.slice(-2)), one("slice_before_start", B.slice(-10, 3)),
        one("slice_row", B.slice(c("i"), c("n"))),
        one("size", B.size("b")), one("size_kb", B.size("kb")),
        one("encode_hex", B.encode("hex")), one("encode_base64", B.encode("base64")),
        case("hello_slices", HELLO, sel(
            B.slice(-6, 3).alias("m6_3"), B.slice(-5, 2).alias("m5_2"), B.slice(-7, 3).alias("m7_3"), B.slice(3, 10).alias("p3_10"),
            B.slice(5, 1).alias("p5_1"), B.slice(6, 1).alias("p6_1"), B.slice(0, 0).alias("p0_0"), B.slice(2).alias("p2"),
            B.slice(-1).alias("m1"), B.slice(-6).alias("m6"), B.head(0).alias("h0"), B.tail(0).alias("t0"), B.head(10).alias("h10"),
            B.tail(10).alias("t10"), B.head(-10).alias("hm10"), B.tail(-10).alias("tm10"), B.head(-5).alias("hm5"), B.tail(-5).alias("tm5"))),
        case("null_arguments", ROWS, sel(B.slice(c("o"), c("l")).alias("slice"), B.head(c("o")).alias("head"), B.get(c("o")).alias("get")),
             note="a null offset or n is null; a null length is the rest"),
        one("get_past_the_ends", B.get(c("i"), null_on_oob=True), AB),
        one("decode_hex", B.decode("hex", strict=False), TEXT),
        one("decode_base64", B.decode("base64", strict=False), B64, note="base64 must be padded"),
        case("reinterpret", REINT, sel(
            B.reinterpret(dtype=pl.Int32).alias("i32"), B.reinterpret(dtype=pl.UInt32).alias("u32"), B.reinterpret(dtype=pl.Int16).alias("i16"),
            B.reinterpret(dtype=pl.Int64).alias("i64"), B.reinterpret(dtype=pl.UInt8).alias("u8"),
            B.reinterpret(dtype=pl.Int32, endianness="big").alias("be"), B.reinterpret(dtype=pl.Date).alias("date"),
            B.reinterpret(dtype=pl.Float64).alias("f64"), B.reinterpret(dtype=pl.Float32).alias("f32")),
            note="a value of another width is null; the least denormal float and a NaN by their bits"),
        one("reinterpret_one", B.reinterpret(dtype=pl.Float64), ONE),
        case("reinterpret_i128", I128, sel(B.reinterpret(dtype=pl.Int128).alias("le"), B.reinterpret(dtype=pl.Int128, endianness="big").alias("be"))),
        # --- generated -----------------------------------------------------------------
        case("bin_gen", gen_bytes, sel(
            B.contains(b"\x00").alias("c0"), B.contains(c("p")).alias("cp"), B.starts_with(c("p")).alias("sw"), B.ends_with(c("p")).alias("ew"),
            B.get(c("i"), null_on_oob=True).alias("gi"), B.head(c("n")).alias("hn"), B.tail(2).alias("t2"), B.slice(c("i"), c("n")).alias("sl"),
            B.slice(-2).alias("sm2"), B.size("b").alias("sz"), B.size("kb").alias("kb"), B.encode("hex").alias("hex"),
            B.encode("base64").alias("b64"))),
        case("reinterpret_4_gen", four, sel(B.reinterpret(dtype=pl.Int32).alias("i32"), B.reinterpret(dtype=pl.UInt32, endianness="big").alias("u32be"),
                                            B.reinterpret(dtype=pl.Float32).alias("f32"), B.reinterpret(dtype=pl.Date).alias("date"),
                                            B.reinterpret(dtype=pl.Int16).alias("i16"))),
        case("reinterpret_8_gen", eight, sel(B.reinterpret(dtype=pl.Int64).alias("i64"), B.reinterpret(dtype=pl.UInt64, endianness="big").alias("u64be"),
                                             B.reinterpret(dtype=pl.Float64).alias("f64"), B.reinterpret(dtype=pl.Datetime("us")).alias("dt"))),
        case("decode_gen", texts, sel(B.decode("hex", strict=False).alias("hex"), B.decode("base64", strict=False).alias("b64")),
             note="odd lengths and digits past f fail to decode; base64 wants its padding"),
    ]
